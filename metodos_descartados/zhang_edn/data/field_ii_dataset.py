"""
Field II dataset loader for PyTorch.

Reads .mat files generated by field_ii/generate_training_data.m.
Each file contains one plane-wave acquisition from one phantom.

Expected .mat structure:
    rf_data       : (n_samples, n_elements) float64
    t_start       : scalar, start time [s]
    fs            : scalar, sampling frequency [Hz]
    fc            : scalar, center frequency [Hz]
    c             : scalar, speed of sound [m/s]
    n_elements    : scalar
    pitch         : scalar [m]
    positions     : (n_scatterers, 3)
    amplitudes    : (n_scatterers, 1)
    phantom_type  : 'points' or 'cysts'
"""

from __future__ import annotations

import numpy as np
import torch
from torch.utils.data import Dataset
from pathlib import Path
from typing import Optional, Dict, List
import scipy.io as sio


def _mat_scalar(mat: dict, key: str, default: float = 0.0) -> float:
    """Safely extract a scalar from a .mat dict."""
    val = mat.get(key)
    if val is None:
        return default
    return float(np.array(val).squeeze())


class FieldIIDataset(Dataset):
    """
    PyTorch Dataset for Field II-generated training data.

    Parameters
    ----------
    data_root : str or Path
        Root directory containing 'points/' and/or 'cysts/' subdirectories.
    phantom_types : list of str
        Which phantom types to include. Default: both.
    normalize : bool
        Normalize RF data by max absolute value.
    align_t_start : bool
        If True, compensates Field II time offset (t_start) so sample index 0
        corresponds to t=0 for the forward model.
    split : str
        One of 'train', 'test', or 'all'.  Files are sorted per phantom type
        before splitting so the split is deterministic and reproducible.
    train_ratio : float
        Fraction of files used for training (default 0.8).  Ignored when
        split='all'.
    max_samples : int or None
        Limit number of loaded files (for quick debugging).
    """

    def __init__(
        self,
        data_root: str | Path,
        phantom_types: Optional[List[str]] = None,
        normalize: bool = True,
        align_t_start: bool = True,
        split: str = "all",
        train_ratio: float = 0.8,
        max_samples: Optional[int] = None,
    ):
        super().__init__()
        self.data_root = Path(data_root)
        self.normalize = normalize
        self.align_t_start = align_t_start

        if split not in ("train", "test", "all"):
            raise ValueError(f"split must be 'train', 'test', or 'all', got '{split}'")

        if phantom_types is None:
            phantom_types = ["points", "cysts"]

        self.file_list: List[Path] = []
        for ptype in phantom_types:
            folder = self.data_root / ptype
            if folder.exists():
                files = sorted(folder.glob("*.mat"))
                if split != "all":
                    n_train = max(1, int(len(files) * train_ratio))
                    if split == "train":
                        files = files[:n_train]
                    else:  # test
                        files = files[n_train:]
                self.file_list.extend(files)

        if max_samples is not None:
            self.file_list = self.file_list[:max_samples]

        if len(self.file_list) == 0:
            print(f"WARNING: No .mat files found in {data_root}")
            print(f"  Looked for subdirectories: {phantom_types}")

    def __len__(self) -> int:
        return len(self.file_list)

    def __getitem__(self, idx: int) -> Dict[str, object]:
        filepath = self.file_list[idx]
        mat = sio.loadmat(str(filepath))

        rf = mat["rf_data"].astype(np.float32)  # (n_samples, n_elements)
        rf = rf.T  # -> (n_elements, n_samples) = (K, D)

        # Read metadata from .mat
        fs = _mat_scalar(mat, "fs", 20.832e6)
        fc = _mat_scalar(mat, "fc", 5.208e6)
        c = _mat_scalar(mat, "c", 1540.0)
        pitch_m = _mat_scalar(mat, "pitch", 304.8e-6)
        n_elements = int(_mat_scalar(mat, "n_elements", rf.shape[0]))
        t_start = _mat_scalar(mat, "t_start", 0.0)

        if self.align_t_start:
            shift = int(np.round(t_start * fs)) if fs > 0 else 0
            if shift != 0:
                K, D = rf.shape
                aligned = np.zeros_like(rf)
                if shift > 0 and shift < D:
                    aligned[:, shift:] = rf[:, : D - shift]
                elif shift < 0 and -shift < D:
                    aligned[:, : D + shift] = rf[:, -shift:]
                rf = aligned

        if self.normalize:
            max_val = np.max(np.abs(rf)) + 1e-12
            rf = rf / max_val

        ptype = str(filepath.parent.name)

        return {
            "rf_data": torch.from_numpy(rf).float(),    # (K, D)
            "angle_deg": torch.tensor(0.0).float(),
            "sequence_name": filepath.stem,
            "category": "field_ii",
            "subcategory": ptype,
            "fs": fs,
            "fc": fc,
            "c": c,
            "pitch_m": pitch_m,
            "n_elements": n_elements,
            "t_start": t_start,
        }
