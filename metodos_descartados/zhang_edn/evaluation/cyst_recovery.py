"""Recover cyst centers and radii from voids in scatterer position arrays.

Field II cyst phantoms are generated by removing background scatterers inside
randomly-placed circular cysts. The cyst centers and radii are NOT saved in
the resulting .mat files, but they leave a measurable signature: the
(x, z) histogram of `positions` has zero/low-count bins forming circular
voids. This module recovers them.

Usage::

    from scipy.io import loadmat
    from zhang_dnn.evaluation.cyst_recovery import histogram_cyst_recovery

    mat = loadmat("cysts_0241.mat")
    positions = mat["positions"]  # (N, 3) in metres, columns x, y, z
    cysts = histogram_cyst_recovery(positions)
    # cysts: list of (cx_mm, cz_mm, radius_mm)

Method:
    1. 2-D histogram of (x, z) with bin_size_mm bins.
    2. Adaptive empty threshold: max(0, mean - 2*std) over non-zero bins.
    3. Morphological closing (3x3, 1 iter) to fill spurious holes.
    4. Connected components (8-connectivity).
    5. Per-component centroid (bin index → physical mm) and effective radius
       from area assuming circular shape.
    6. Filter by radius range [min_radius_mm, max_radius_mm].
"""

from __future__ import annotations

import numpy as np
from scipy.ndimage import binary_closing, label


def histogram_cyst_recovery(
    positions: np.ndarray,
    x_range_mm: tuple[float, float] = (-20.0, 20.0),
    z_range_mm: tuple[float, float] = (5.0, 45.0),
    bin_size_mm: float = 0.4,
    min_radius_mm: float = 2.0,
    max_radius_mm: float = 8.0,
) -> list[tuple[float, float, float]]:
    """Recover (center_x_mm, center_z_mm, radius_mm) for each cyst in the phantom.

    Parameters
    ----------
    positions : (N, 3) float array of [x, y, z] in METRES.
    x_range_mm, z_range_mm : physical extent of the search region.
    bin_size_mm : histogram bin size in mm. 0.4 mm gives ~5 scatterers/bin
        for a phantom with ~20/mm³ density and 2 mm elevation.
    min_radius_mm, max_radius_mm : reject components outside this range.

    Returns
    -------
    list of (cx_mm, cz_mm, radius_mm).
    """
    if positions.size == 0:
        return []
    x_mm = positions[:, 0] * 1e3
    z_mm = positions[:, 2] * 1e3

    nx_bins = int(round((x_range_mm[1] - x_range_mm[0]) / bin_size_mm))
    nz_bins = int(round((z_range_mm[1] - z_range_mm[0]) / bin_size_mm))
    x_edges = np.linspace(x_range_mm[0], x_range_mm[1], nx_bins + 1)
    z_edges = np.linspace(z_range_mm[0], z_range_mm[1], nz_bins + 1)

    H, _, _ = np.histogram2d(x_mm, z_mm, bins=[x_edges, z_edges])

    nonzero = H[H > 0]
    if nonzero.size == 0:
        return []
    bg_mean = float(nonzero.mean())
    bg_std = float(nonzero.std())
    empty_threshold = max(0.0, bg_mean - 2.0 * bg_std)
    empty_mask = H <= empty_threshold

    closed = binary_closing(empty_mask, structure=np.ones((3, 3), dtype=bool),
                            iterations=1)

    labeled, n_components = label(closed, structure=np.ones((3, 3), dtype=bool))

    cysts: list[tuple[float, float, float]] = []
    for cid in range(1, n_components + 1):
        comp = np.argwhere(labeled == cid)  # (n, 2): (xi, zi)
        if comp.shape[0] < 4:
            continue
        cent_xi = float(comp[:, 0].mean())
        cent_zi = float(comp[:, 1].mean())

        cx_mm = x_edges[0] + bin_size_mm * (cent_xi + 0.5)
        cz_mm = z_edges[0] + bin_size_mm * (cent_zi + 0.5)

        area_mm2 = comp.shape[0] * (bin_size_mm ** 2)
        radius_mm = float(np.sqrt(area_mm2 / np.pi))

        if min_radius_mm <= radius_mm <= max_radius_mm:
            cysts.append((cx_mm, cz_mm, radius_mm))

    return cysts
